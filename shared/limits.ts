// Ограничения на данные, общие для клиента и сервера.
//
// Почему файл лежит в отдельной папке shared/, а не в client или server:
// эти числа ОБЯЗАНЫ совпадать с обеих сторон. Клиент по ним подсказывает
// пользователю (maxLength, счётчик символов), сервер по ним проверяет запросы.
// Если бы у каждой стороны была своя копия, однажды поменяли бы одну и забыли
// другую: клиент разрешил бы ввести 30 символов, а сервер отвечал бы 400.
// Один файл = одно место для изменения.
//
// Здесь только простые числа без импортов: файл подключают и Vite (клиент),
// и Node (сервер), поэтому он не должен зависеть ни от браузера, ни от Node.

// ---------- Пользователь ----------

// Максимальная длина email по стандарту (RFC 5321)
export const EMAIL_MAX = 254;

export const PASSWORD_MIN = 8;
// bcrypt учитывает только первые 72 байта пароля, поэтому длиннее не принимаем
export const PASSWORD_MAX = 72;

// ---------- Растение ----------

export const PLANT_NAME_MAX = 25;

// Эмодзи может состоять из нескольких символов (например, 🌶️ это 2),
// поэтому лимит с запасом. Защищает сервер от мусора вместо эмодзи.
export const PLANT_EMOJI_MAX = 12;

// Период полива в днях.
// ВНИМАНИЕ: те же числа записаны в server/src/db/schema.sql (CHECK BETWEEN 1 AND 365).
// SQL-файл не умеет импортировать из TypeScript, поэтому там их нужно менять вручную.
export const INTERVAL_MIN = 1;
export const INTERVAL_MAX = 365;
